use rustls::pki_types::EchConfigListBytes;
use rustls::client::EchConfig;

#[test]
fn parse_real_cloudflare_ech_config() {
    let bytes: Vec<u8> = vec![
        0x00, 0x45, 0xfe, 0x0d, 0x00, 0x41, 0xd5, 0x00, 0x20, 0x00, 0x20, 0xc1, 0x5c, 0x0d, 0xc7,
        0x7c, 0x1a, 0x06, 0xfd, 0xc9, 0x67, 0x3c, 0x40, 0x4f, 0x84, 0x98, 0xb7, 0x84, 0x44, 0x93,
        0x70, 0xbf, 0xfe, 0x2c, 0x83, 0x73, 0xd9, 0xc2, 0x71, 0xbb, 0x95, 0x6e, 0x42, 0x00, 0x04,
        0x00, 0x01, 0x00, 0x01, 0x00, 0x12, 0x63, 0x6c, 0x6f, 0x75, 0x64, 0x66, 0x6c, 0x61, 0x72,
        0x65, 0x2d, 0x65, 0x63, 0x68, 0x2e, 0x63, 0x6f, 0x6d, 0x00, 0x00,
    ];
    let list = EchConfigListBytes::from(bytes.as_slice());
    let result = EchConfig::new(list, rustls::crypto::aws_lc_rs::hpke::ALL_SUPPORTED_SUITES);
    println!("EchConfig::new result: {:?}", result.as_ref().map(|_| "ok"));
    assert!(result.is_ok(), "expected valid config, got {:?}", result.err());
}
